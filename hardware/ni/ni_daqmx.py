"""
NI DAQmx acquisition driver (USB-6451) — driver code ``ni_daqmx_v1``.

The device samples its analog inputs on an *external digital sample clock*:
the CONV_START signal generated by the timing device (the Pico) drives
``/<device>/PFI2`` (screw terminal 28; D GND on 27), so every conversion
happens on a rising edge decided by the
the timing hardware.  This makes "exactly N = T_int/dt + 1 samples per
integration window" a hardware guarantee — the ramp-storage window
extractor chunks on exactly that contract.  Because the Pico's CONV_START
is a 3.3 V signal and the 6451's shared digital logic family defaults to
5 V (guaranteed VIH 3.66 V — out of spec for 3.3 V drive), ``connect()``
switches the family to 3.3 V before anything is armed.

Consequently this driver only makes sense in ``ramp``/``markers`` timing
mode (a split setup: a µC times, the NI card acquires): ``start_measurement``
refuses to run without a ``ramp_sink`` — with an external clock there is no
internal-clock stream to fall back to.

Input terminals are hardware facts (see USB-6451 manual: one ADC per
differential pair AI<n>/AI<n+8>, simultaneous sampling; DIO/PFI lines may
drive the AI sample clock).  The config selects per channel the
*termination* and may override the physical terminal via ``adc_input``
(e.g. ``"AI6"`` for a referenced-single-ended channel on AI6); without an
override the bench defaults hardcoded here apply:

    ch1 differential -> ai7 (+, AI7) with AI15 (−)
    ch2 differential -> ai1 (+, AI1) with AI9 (−)
    ch1 rse          -> ai0 (AI0 referenced single-ended — bench wiring:
                        the differential pair moved to AI7/AI15, freeing
                        AI0 for the single-ended test signal)
    ch2 rse          -> ai3 (AI3 referenced single-ended)

Every terminal carries its own ADC, so any mix of distinct terminals is
simultaneous at 1 MS/s per channel (never the 500 kS/s
dual-channel-scan case).

Out-of-range readings simply clamp (NI semantics): railing at ±full scale
is the overflow indication — no sentinel is injected.

The ``nidaqmx`` package is imported lazily: the app (and the registry) work
on machines without it; only ``connect()``/``start_measurement`` need it.
"""
import logging
import re
import threading
import time

import numpy as np

from hardware.config.schema import VoltageRange
from hardware.interfaces.acquisition import IDataAcquisition

logger = logging.getLogger(__name__)

# Read loop: target one read every ~20 ms of samples at high rates; at LOW
# rates (markers mode: rate = 1/T_int) as few as one sample per read — a
# large floor would deliver the live pipeline in ~100 s lumps and strand up
# to a block of windows in the DAQmx buffer at stop (measurement rows in
# markers mode).
TARGET_BLOCK_SECONDS = 0.02
MAX_BLOCK_SAMPLES = 1 << 20

# Host-side DAQmx buffer: sized explicitly from the expected rate (samples
# per channel) instead of leaving the DAQmx default.  The buffer is the
# first line of defense against host hiccups (GUI stalls share the GIL
# with this Python reader) — an overrun fails the acquisition, so give it
# a few seconds of slack, bounded in memory.
BUFFER_SECONDS = 5.0
MIN_BUFFER_SAMPLES = 10_000
MAX_BUFFER_SAMPLES = 50_000_000

# Read timeout, bounded: it is the armed-but-no-edges watchdog during the
# run and keeps stop responsive (the stop drain must complete before
# task.stop() discards whatever the buffer still holds).
MIN_READ_TIMEOUT_S = 0.5
MAX_READ_TIMEOUT_S = 2.0

# Total-silence watchdog: read timeouts while armed are swallowed by
# design, so a dead CONV_START line needs its own loud WARNING (one per
# interval while the stall persists).  5 s >> the normal task-start →
# timing-'S' gap (<< 1 s) and << one integration window of the slowest
# realistic ramp campaign.
STALL_WARN_S = 5

# DAQmx "samples requested were not available before the timeout expired":
# while armed with an external clock this just means "no CONV_START edges
# yet" — the reader keeps waiting instead of failing the measurement.
READ_TIMEOUT_CODE = -200284


class NIDAQmxAcquisition(IDataAcquisition):
    """Acquisition role on a NI USB-6451 (DAQmx device, USB transport)."""

    DRIVER_CAPABILITIES = {"acquisition"}
    IS_VIRTUAL = False

    # Hardcoded layer-1 limits (validated against the config at load time)
    ADC_BITS = 20
    ADC_NATIVE_RANGE = VoltageRange(min_volts=-10.0, max_volts=10.0)
    INPUT_RANGES = (
        VoltageRange(min_volts=-10.0, max_volts=10.0),
        VoltageRange(min_volts=-5.0, max_volts=5.0),
        VoltageRange(min_volts=-2.5, max_volts=2.5),
        VoltageRange(min_volts=-0.2, max_volts=0.2),
    )
    MAX_CHANNELS = 2            # exposed by this app (physical: 8 diff / 16 SE)
    MAX_RATE_HZ = 1_000_000.0   # per channel, simultaneous sampling
    CHANNEL_TERMINATIONS = ("differential", "rse")

    # Bench-default wiring (applied when the config carries no adc_input
    # override; change here if the cabling changes):
    # (channel, termination) -> DAQmx terminal of the positive input
    CHANNEL_TERMINALS = {
        ("ch1", "differential"): "ai7",   # AI7 (+) / AI15 (−)
        ("ch2", "differential"): "ai1",   # AI1 (+) / AI9 (−)
        ("ch1", "rse"): "ai0",            # AI0 (ADC 0 — no SE-pair conflict)
        ("ch2", "rse"): "ai3",
    }
    # Physical inputs of the card: AI0..AI15, differential measured on a
    # pair AI<n>(+)/AI<n+8>(−) so the positive terminal must be AI0..AI7
    # (the negative is implied by DAQmx's DIFF configuration); RSE is
    # legal on any terminal.
    MAX_AI_TERMINAL = 15
    MAX_DIFF_POSITIVE_TERMINAL = 7
    # CONV_START from the timing device: digital, 3.3 V, rising edge.
    # Wired to PFI2 = screw terminal 28 on the AO/DIO connector (chosen
    # over PFI0/terminal 25 for the bench: adjacent to D GND terminal 27
    # for the signal/ground pair, and away from the +5 V pin 24).  The
    # 6451's shared digital logic family defaults to 5 V, whose
    # guaranteed VIH is 3.66 V — below the Pico's 3.3 V high — so
    # connect() sets the family to 3.3 V (VIH >= 2.0 V) before anything
    # is armed.  The family is a digital-PORT attribute (shared by all
    # lines of the device): it is set on port0, the port owning every
    # PFI/P0 line — "PFI2" names the routing terminal of the clock
    # source, not a physical channel, and is rejected by
    # Dig.PortLogicFamily (DAQmx -200170, live finding on the card).
    CONV_START_TERMINAL = "PFI2"
    CONV_START_PORT = "port0"
    CONV_START_EDGE = "rising"
    CONV_START_LOGIC_FAMILY = "THREE_POINT_THREE_V"

    def __init__(self, device_name: str = ""):
        self._device_name = device_name
        self._connected = False
        self._product_type = None
        self._channel_plan = []          # ordered [(channel_id, termination[, adc_input])]
        self._channel_terminals = []     # resolved DAQmx terminal per plan entry
        self._input_range = self.INPUT_RANGES[1]  # default ±5 V
        self._task = None
        self._thread = None
        self._stop_event = threading.Event()
        self._error = False
        self._samples_read = 0

    # ------------------------------------------------------------- plumbing

    @property
    def is_connected(self) -> bool:
        return self._connected

    @property
    def is_measuring(self) -> bool:
        return self._thread is not None and self._thread.is_alive()

    @property
    def error(self) -> bool:
        """True once the reader thread hit a fatal error (surfaced by
        stop_measurement's return; polled live by the ramp-analysis UI)."""
        return self._error

    def connect(self) -> bool:
        try:
            from nidaqmx.constants import LogicFamily
            from nidaqmx.system import PhysicalChannel, System
        except ImportError:
            logger.error(
                "connect failed: the 'nidaqmx' Python package is not "
                "installed on this machine"
            )
            return False
        try:
            devices = {dev.name: dev for dev in System.local().devices}
        except Exception:
            logger.exception("DAQmx: could not enumerate devices (driver installed?)")
            return False
        device = devices.get(self._device_name)
        if device is None:
            found = ", ".join(sorted(devices)) or "none found"
            logger.error(
                "DAQmx device %r not found (present: %s)", self._device_name, found
            )
            return False
        try:
            device.self_test_device()
        except Exception:
            logger.exception("DAQmx device %r failed its self-test", self._device_name)
            return False
        # PFI input levels must accept the Pico's 3.3 V CONV_START: the
        # shared logic family defaults to 5 V (VIH >= 3.66 V — out of
        # spec for a 3.3 V driver).  A port attribute, shared by all
        # digital lines: set on the port owning the clock line.
        try:
            PhysicalChannel(
                f"{self._device_name}/{self.CONV_START_PORT}"
            ).dig_port_logic_family = getattr(LogicFamily, self.CONV_START_LOGIC_FAMILY)
        except Exception:
            logger.exception(
                "DAQmx: could not set the digital logic family to 3.3 V on "
                "%s/%s", self._device_name, self.CONV_START_PORT
            )
            return False
        self._product_type = device.product_type
        self._connected = True
        logger.info(
            "Connected to DAQmx device %r (%s)", self._device_name, self._product_type
        )
        return True

    def disconnect(self) -> bool:
        self._connected = False
        return True

    # ---------------------------------------------------------- ADC config

    # ------------------------------------------------ channel->terminal map

    @classmethod
    def _parse_adc_input(cls, adc_input, termination: str):
        """Normalize a config ``adc_input`` ("AI6"/"ai6") to a DAQmx
        terminal name, or None when the card has no such input for the
        termination: differential needs the positive terminal of a pair
        (AI0..AI7 — the negative AI<n+8> is implied by DAQmx's DIFF
        configuration), RSE is legal on AI0..AI15."""
        match = re.fullmatch(r"ai(\d+)", str(adc_input).strip().lower())
        if match is None:
            return None
        index = int(match.group(1))
        limit = (
            cls.MAX_DIFF_POSITIVE_TERMINAL
            if termination == "differential"
            else cls.MAX_AI_TERMINAL
        )
        if index > limit:
            return None
        return f"ai{index}"

    @classmethod
    def _resolve_terminals(cls, channel_plan):
        """Resolve every plan entry to its DAQmx terminal: the config's
        ``adc_input`` override when given, else the bench default for the
        (channel, termination) pair.  Returns (terminals, errors); errors
        name the config path of the offending entry."""
        terminals, errors = [], []
        claimed = {}
        for entry in channel_plan or []:
            channel_id, termination = entry[0], entry[1]
            adc_input = entry[2] if len(entry) > 2 else None
            terminal = cls.CHANNEL_TERMINALS.get((channel_id, termination))
            if terminal is None:
                errors.append(
                    f"channels.{channel_id}: no input terminal for "
                    f"({channel_id!r}, {termination!r}) — valid pairs: "
                    f"{sorted(f'{c}/{t}' for c, t in cls.CHANNEL_TERMINALS)}"
                )
                continue
            if adc_input is not None:
                parsed = cls._parse_adc_input(adc_input, termination)
                if parsed is None:
                    errors.append(
                        f"channels.{channel_id}.adc_input: {adc_input!r} is not "
                        f"a USB-6451 input for a {termination} channel "
                        f"(differential: AI0..AI7, the positive of the "
                        f"AI<n>/AI<n+8> pair; rse: AI0..AI15)"
                    )
                    continue
                terminal = parsed
            if terminal in claimed:
                errors.append(
                    f"channels: input terminal {terminal.upper()} used by both "
                    f"{claimed[terminal]} and {channel_id}"
                )
                continue
            claimed[terminal] = channel_id
            terminals.append(terminal)
        return terminals, errors

    @classmethod
    def validate_channel_plan(cls, channel_plan) -> list:
        """Config-load check of a channel plan [(channel_id, termination[,
        adc_input]), …]: empty list = the driver can wire it.  Exposed to
        the loader through the registry so an impossible wiring fails the
        load instead of the measurement start."""
        return cls._resolve_terminals(channel_plan)[1]

    def configure_channels(self, channel_plan) -> bool:
        """Map the config's channels onto the card's input terminals.

        Entries are (channel_id, termination) tuples, optionally with a
        third element ``adc_input`` naming the physical terminal (e.g.
        "AI6") — it overrides the bench default for that
        (channel, termination)."""
        plan = list(channel_plan or [])
        if not plan:
            logger.error("configure_channels: empty channel plan")
            return False
        terminals, errors = self._resolve_terminals(plan)
        if errors:
            for error in errors:
                logger.error("configure_channels: %s", error)
            return False
        self._channel_plan = plan
        self._channel_terminals = terminals
        logger.info("DAQmx channel plan: %s -> %s", plan, terminals)
        return True

    def set_input_range(self, min_volts: float, max_volts: float) -> bool:
        requested = VoltageRange(min_volts=float(min_volts), max_volts=float(max_volts))
        for allowed in self.INPUT_RANGES:
            if allowed == requested:
                self._input_range = allowed
                return True
        logger.error(
            "set_input_range rejected: %s V is not a USB-6451 range "
            "(valid: %s)", requested, ", ".join(str(r) for r in self.INPUT_RANGES)
        )
        return False

    def get_adc_settings(self) -> dict:
        return {
            "bits": self.ADC_BITS,
            "num_channels": None,  # filled by the manager from the config
            "input_range_volts": {
                "min_volts": self._input_range.min_volts,
                "max_volts": self._input_range.max_volts,
            },
            "supports_oversampling": False,
        }

    # ------------------------------------------------------------- measure

    def start_measurement(self, session_model, data_model, ramp_sink=None) -> bool:
        if ramp_sink is None:
            logger.error(
                "start_measurement refused: this driver is clocked by the "
                "external CONV_START signal and can only stream ramp/markers "
                "data (no internal-clock mode)"
            )
            return False
        if self.is_measuring:
            logger.error("start_measurement refused: already measuring")
            return False
        if not self._channel_plan:
            logger.error("start_measurement refused: no channel plan configured")
            return False

        try:
            import nidaqmx
            from nidaqmx.constants import (
                AcquisitionType,
                Edge,
                TerminalConfiguration,
            )
            from nidaqmx.stream_readers import AnalogMultiChannelReader
        except ImportError:
            logger.error(
                "start_measurement failed: the 'nidaqmx' Python package is "
                "not installed on this machine"
            )
            return False

        expected_rate = self._expected_rate_hz(session_model)
        block = self._block_size(expected_rate)

        # One voltage channel per configured input, on its resolved
        # terminal (config adc_input override or bench default).
        task = nidaqmx.Task()
        try:
            terminal_config_map = {
                "differential": TerminalConfiguration.DIFF,
                "rse": TerminalConfiguration.RSE,
            }
            for entry, terminal in zip(self._channel_plan, self._channel_terminals):
                task.ai_channels.add_ai_voltage_chan(
                    f"{self._device_name}/{terminal}",
                    terminal_config=terminal_config_map[entry[1]],
                    min_val=self._input_range.min_volts,
                    max_val=self._input_range.max_volts,
                )
            # Every conversion on a rising CONV_START edge from the timing
            # device: N = T_int/dt + 1 samples per integration window, exact.
            task.timing.cfg_samp_clk_timing(
                rate=expected_rate,
                source=f"/{self._device_name}/{self.CONV_START_TERMINAL}",
                active_edge=Edge.RISING,
                sample_mode=AcquisitionType.CONTINUOUS,
            )
            # Explicit host buffer (samples per channel): the DAQmx default
            # is derived from the rate it is told, and an undersized buffer
            # turns a transient host stall into a fatal acquisition error.
            task.in_stream.input_buf_size = self._buffer_size(expected_rate)
        except Exception:
            logger.exception("DAQmx task configuration failed")
            try:
                task.close()
            except Exception:
                pass
            return False

        self._task = task
        self._reader = AnalogMultiChannelReader(task.in_stream)
        # Explicit-count reads into the oversized buffer (n = min(avail,
        # block) <= buffer width, guaranteed by construction): the
        # wrapper's array verification demands an EXACT (chans, count)
        # shape — which a fixed buffer violates for every count != block,
        # READ_ALL included (it resolves to avail) — so it is disabled.
        self._reader.verify_array_shape = False
        self._stop_event.clear()
        self._error = False
        self._samples_read = 0

        # Arm the task BEFORE returning: the 6451 ignores CONV_START edges
        # while no acquisition is in progress, so the caller may only send
        # the timing start command ('S' to the Pico) once this task is
        # armed.  Then the first edge after 'S' — the first integration
        # edge of window 0 (firmware: edges at 0, dt, ..., T_int, none
        # during reset) — is the first converted sample, which is exactly
        # the alignment the ramp sink's window extractor assumes.
        try:
            task.start()
        except Exception:
            logger.exception("DAQmx task start failed")
            try:
                task.close()
            except Exception:
                pass
            self._task = None
            return False

        self._thread = threading.Thread(
            target=self._read_loop,
            args=(session_model, ramp_sink, block, expected_rate),
            daemon=True,
            name="ni-daqmx-reader",
        )
        self._thread.start()
        logger.info(
            "DAQmx task started: %d channel(s) %s, external clock %s, "
            "expected rate %.6g Hz, block %d, buffer %d samples/ch, "
            "input range [%.3g, %.3g] V",
            len(self._channel_plan), self._channel_terminals,
            self.CONV_START_TERMINAL, expected_rate, block,
            self._buffer_size(expected_rate),
            self._input_range.min_volts, self._input_range.max_volts,
        )
        return True

    def stop_measurement(self) -> bool:
        # Ask the reader to stop and WAIT for it first: its bounded read
        # timeout (<= 2 s) unblocks it, and it then drains everything the
        # DAQmx buffer still holds before this method calls task.stop() —
        # which would discard unread samples (measurement rows in markers
        # mode).  task.stop() afterwards also unblocks a wedged reader.
        self._stop_event.set()
        if self._thread is not None and self._thread.is_alive():
            self._thread.join(timeout=6.0)
        if self._task is not None:
            try:
                self._task.stop()
            except Exception:
                pass  # already stopped / never started streaming
        ok = True
        if self._task is not None:
            try:
                self._task.close()
            except Exception:
                logger.exception("DAQmx task close failed")
                ok = False
            self._task = None
        if self._error:
            ok = False
        logger.info("DAQmx stop_measurement: %d samples read, reader error=%s -> %s",
                    self._samples_read, self._error, "ok" if ok else "FAILED")
        return ok

    # ------------------------------------------------------------- reader

    def _read_loop(self, session, ramp_sink, block, expected_rate):
        buffer = np.empty((len(self._channel_plan), block), dtype=np.float64)
        # volts -> zero-based uint32 counts over the applied bipolar range
        vmin = self._input_range.min_volts
        full = float(2**self.ADC_BITS - 1)
        scale = full / (self._input_range.max_volts - vmin)

        # plan entries are (channel_id, termination[, adc_input]) — index [0]
        channel_indices = [0 if entry[0] == "ch1" else 1 for entry in self._channel_plan]
        counters = [0] * len(self._channel_plan)
        wait_timeout = self._read_timeout_s(1, expected_rate)

        def deliver(count):
            view = buffer[:, :count]
            # zero-based counts over the applied bipolar range; NI clamps
            # out-of-range readings, so railing at full scale *is* the
            # overflow indication
            scaled = np.rint((view - vmin) * scale)
            np.clip(scaled, 0.0, full, out=scaled)
            counts = scaled.astype(np.uint32)
            for row, ch_index in enumerate(channel_indices):
                ramp_sink.write_block(ch_index, counts[row], counters[row])
                counters[row] += count
            self._samples_read += count

        def read_count(n, timeout):
            """Read exactly n samples and deliver them to the sink.
            Returns the number of samples delivered.  On a read timeout,
            the samples DAQmx already transferred (and removed from its
            buffer) are delivered — dropping them would silently shift
            the window grid, because the sink counters would not advance
            (B31)."""
            try:
                read = self._reader.read_many_sample(buffer, n, timeout=timeout)
            except Exception as exc:
                if getattr(exc, "error_code", None) != READ_TIMEOUT_CODE:
                    raise
                read = int(getattr(exc, "samps_per_chan_read", 0) or 0)
            if read > 0:
                deliver(read)
            return read

        in_stream = self._task.in_stream
        # Silence watchdog: the armed-but-no-edges state is LEGAL only for
        # the short window between task.start() and the timing 'S' — but a
        # read timeout there is swallowed by design (read_count returns 0),
        # so a dead CONV_START line or a stalled timing engine would
        # otherwise look like a perfectly healthy, perfectly empty run.
        # Any total stall longer than STALL_WARN_S gets a WARNING (and one
        # again every STALL_WARN_S while it persists).
        last_progress_samples = 0
        last_progress_t = time.monotonic()
        try:
            while not self._stop_event.is_set():
                avail = in_stream.avail_samp_per_chan
                if avail <= 0:
                    # Armed but no CONV_START edges yet: block on one
                    # sample (this read is the no-edges watchdog; its
                    # timeout transfers nothing).
                    read_count(1, wait_timeout)
                    now = time.monotonic()
                    if self._samples_read > last_progress_samples:
                        last_progress_samples = self._samples_read
                        last_progress_t = now
                    elif now - last_progress_t >= STALL_WARN_S:
                        logger.warning(
                            "DAQmx reader: NO samples for %.0f s (total %d) "
                            "— task armed but no CONV_START edges: timing "
                            "engine running? PFI2 wiring? (repeats every %d s "
                            "while stalled)",
                            now - last_progress_t, self._samples_read,
                            STALL_WARN_S,
                        )
                        last_progress_t = now
                    continue
                # Explicit count — never READ_ALL_AVAILABLE: the wrapper
                # resolves it to avail_samp_per_chan and its array check
                # demands the buffer be shaped (chans, avail) EXACTLY,
                # which the fixed oversized buffer never is (B30).  With
                # n = min(avail, block) the samples are already in the
                # buffer, so the read returns completely.
                read_count(min(avail, block), MAX_READ_TIMEOUT_S)

            # Final drain (the timing engine is stopped FIRST by
            # stop_receiving, so the buffer is static): everything DAQmx
            # still holds must reach the sink BEFORE stop_measurement
            # calls task.stop(), which discards unread samples — in
            # markers mode those are measurement rows, not monitoring
            # data.
            while True:
                try:
                    avail = in_stream.avail_samp_per_chan
                except Exception:
                    break
                if avail <= 0:
                    break
                if read_count(min(avail, block), 0.1) <= 0:
                    break
        except Exception:
            # Anything escaping the loop above is fatal for the stream —
            # surface it and stop (timeouts are handled in read_count).
            if not self._stop_event.is_set():
                logger.exception("DAQmx read failed after %d samples", self._samples_read)
                self._error = True
        if self._error:
            logger.error("DAQmx reader finished WITH ERRORS after %d samples",
                         self._samples_read)
        else:
            logger.info("DAQmx reader finished: %d samples delivered to the sink",
                        self._samples_read)

    # ------------------------------------------------------------- helpers

    def _expected_rate_hz(self, session) -> float:
        """Nominal stream rate from the session timing (used for buffer
        sizing and read timeouts; the true rate is set by CONV_START).
        The session carries the APPLIED values from the timing driver's
        mirror — dt is the effective (quantized) dt and int the quantized
        integration time, so the sizing matches what the edges will do."""
        mode = getattr(session, "timing_mode", "ramp")
        if mode == "markers":
            dt_s = getattr(session, "int_time", 0.001)
        else:
            dt_s = getattr(session, "ramp_dt_s", 0.0) or 1e-6
        return 1.0 / dt_s if dt_s > 0 else 1e6

    @staticmethod
    def _buffer_size(rate_hz: float) -> int:
        """Host buffer in samples per channel: ~BUFFER_SECONDS of stream,
        bounded to keep memory sane (the property counts per channel)."""
        if not rate_hz or rate_hz <= 0:
            return MIN_BUFFER_SAMPLES
        return max(
            MIN_BUFFER_SAMPLES,
            min(int(rate_hz * BUFFER_SECONDS), MAX_BUFFER_SAMPLES),
        )

    @staticmethod
    def _read_timeout_s(block: int, rate_hz: float) -> float:
        """Read timeout ~10 block times, bounded to [0.5, 2] s: during the
        run it is the armed-but-no-edges watchdog; at stop it bounds how
        long the drain waits before the loop notices the stop event."""
        if not rate_hz or rate_hz <= 0:
            return MAX_READ_TIMEOUT_S
        return min(max(10.0 * block / rate_hz, MIN_READ_TIMEOUT_S), MAX_READ_TIMEOUT_S)

    @staticmethod
    def _block_size(rate_hz: float) -> int:
        """Samples per read: ~TARGET_BLOCK_SECONDS worth at high rates; as
        few as ONE at low rates (markers mode: rate = 1/T_int)."""
        if not rate_hz or rate_hz <= 0:
            return 20_000
        return max(1, min(int(rate_hz * TARGET_BLOCK_SECONDS), MAX_BLOCK_SAMPLES))
